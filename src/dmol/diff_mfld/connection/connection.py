class Connection(metaclass=PartialSpec):
    _bundle: type[VectorBundle]
    _coeffs_shape: Tuple[int, ...]

    def __class_getitem__(cls, args):
        bundle: type[VectorBundle] = args

        # NOTE: for now we will disallow defining connections on tensor product bundles for simplicity as there is no
        # current use case or need given we just need to parallel transport simplisitc quantities

        if issubclass(bundle, TensorProductBundle):
            raise NotImplemented(
                "tensor products bundles are not currently supported by connections"
            )

        n = bundle.base.dim if not bundle.incomplete else None
        r = bundle.rank

        coeffs_shape = (r, r, n)

        namespace = {"_bundle": bundle, "_coeffs_shape": coeffs_shape}
        if bundle.incomplete:
            namespace.update(
                {"__class_getitem__": Connection._partial_spec_mfld_pass_to_base}
            )

        return PartialSpec(
            f"Connection[{bundle.__name__}]",
            (cls,),
            namespace,
            creating_derived=True,
        )

    def _partial_spec_mfld_pass_to_base(cls, args):
        underlying_base: type[Manifold] = args
        upd_bundle = cls._bundle[underlying_base]

        n = upd_bundle.base.dim
        r = upd_bundle.rank
        coeffs_shape = (r, r, n)

        return PartialSpec(
            f"Connection[{upd_bundle.__name__}]",
            (cls,),
            {"_bundle": upd_bundle, "_coeffs_shape": coeffs_shape},
            creating_derived=True,
            top_level_type=cls._top_level_type,
        )

    def __init__(self):
        if type(self) == Connection:
            raise TypeError(
                "connectinos cannot be instantiated without being subclassed"
            )
        self._cfg = ConnectionMethodConfig()  # defaults

    @classproperty
    def bundle(cls):
        return cls._bundle

    @property
    def cfg(self):
        return self._cfg

    def coeffs(self, p: Union[Point[Self._bundle.base], torch.Tensor]) -> torch.Tensor:
        p = Point[self._bundle.base](p)  # ensures that the point is compatible
        coeffs = self.eval(p)
        if coeffs.shape != self._coeffs_shape:
            raise ValueError(
                f"connection coefficients generated by {self.__class__.__name__} is incorrect shape"
            )
        return coeffs

    def partials(
        self, p: Union[Point[Self._bundle.base], torch.Tensor]
    ) -> torch.Tensor:
        p = Point[self._bundle.base](p)
        partials = self.eval_partials(p.p)

        n = self._bundle.base.dim
        r = self._bundle.rank
