class BundleCurve:
    _bundle: type[VectorBundle]

    def __class_getitem__(cls, args):
        bundle: type[VectorBundle] = args

        namespace = {"_bundle": bundle}
        if bundle.incomplete:
            namespace.update(
                {"__class_getitem__": BundleCurve._partial_spec_mfld_pass_to_base}
            )

        return PartialSpec(
            f"BundleCurve[{bundle.__name__}]",
            (BundleCurve,),
            namespace,
            creating_derived=True,
        )

    def _partial_spec_mfld_pass_to_base(cls, args):
        underlying_manifold: type[Manifold] = args

        upd_bundle = cls._bundle[underlying_manifold]
        namespace = {"_bundle": upd_bundle}

        if upd_bundle.incomplete:
            namespace.update(
                {"__class_getitem__": BundleCurve._partial_spec_mfld_pass_to_base}
            )

        return PartialSpec(
            f"BundleCurve[{upd_bundle.__name__}]",
            (BundleCurve,),
            namespace,
            creating_derived=True,
            top_level_type=cls._top_level_type,
        )

    def __init__(
        self, t: torch.Tensor, coords: torch.Tensor, derivs: Tuple[torch.Tensor, ...]
    ):
        self._t = t
        self._coords = coords
        self._derivs = derivs

    @property
    def t(self):
        return self._t

    @property
    def coords(self):
        return self._coords

    @property
    def derivs(self):
        return self._derivs


